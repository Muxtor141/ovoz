// Generates the Dart bindings for the Android engine's Kotlin interface.
//
// Run `tool/generate_bindings.sh android`, which first compiles the Kotlin
// classes this reads.
import 'dart:io';

import 'package:jnigen/jnigen.dart';
import 'package:logging/logging.dart';

final _root = Platform.script.resolve('../');

Future<void> main() async {
  Logger.root.level = Level.WARNING;
  Logger.root.onRecord.listen((r) => stderr.writeln('${r.level.name}: ${r.message}'));
  await JniGenerator(
    input: Input(
      // The engine's public API only: everything else in the Kotlin code is
      // internal to it.
      classes: [
        'uz.sayma.ovoz.OvozItem',
        'uz.sayma.ovoz.OvozPlayer',
        'uz.sayma.ovoz.OvozPlayerListener',
        'uz.sayma.ovoz.OvozSession',
        'uz.sayma.ovoz.OvozSessionListener',
      ],
      // Compiled by the example app's Gradle build (the plugin's own build
      // directory lives under it).
      classPath: [_root.resolve('example/build/ovoz/tmp/kotlin-classes/debug/')],
    ),
    output: Output(
      dart: DartOutput(
        path: _root.resolve('lib/src/platform/android/ovoz_bindings.g.dart'),
        structure: OutputStructure.singleFile,
      ),
      // The width marker keeps generated code independent of the package's
      // formatter settings, so regenerating it gives no spurious diffs.
      preamble: '// Generated by tool/generate_bindings.sh. Do not edit.\n// dart format width=80',
    ),
  ).generate(logger: Logger.root);
}
